CREATE TABLE USUARIO (
                         ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         USERNAME VARCHAR2(50) NOT NULL UNIQUE,
                         SENHA_HASH VARCHAR2(100) NOT NULL
);

CREATE TABLE CATEGORIA (
                           ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           CODIGO VARCHAR2(30) NOT NULL UNIQUE,
                           NOME VARCHAR2(100) NOT NULL,
                           DESCRICAO VARCHAR2(300) NOT NULL,
                           PRIORIDADE VARCHAR2(30) NOT NULL
);

CREATE TABLE PONTO (
                       ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       CATEGORIA_ID NUMBER NOT NULL REFERENCES CATEGORIA(ID),
                       USUARIO_ID NUMBER NOT NULL REFERENCES USUARIO(ID),
                       LATITUDE NUMBER(9,6) NOT NULL,
                       LONGITUDE NUMBER(9,6) NOT NULL,
                       DESCRICAO VARCHAR2(500) NOT NULL,
                       RESOLVIDO NUMBER(1) DEFAULT 0 NOT NULL CHECK (RESOLVIDO IN (0,1)),
                       CRIADO_EM TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE COMENTARIO (
                            ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            PONTO_ID NUMBER NOT NULL REFERENCES PONTO(ID) ON DELETE CASCADE,
                            USUARIO_ID NUMBER NOT NULL REFERENCES USUARIO(ID),
                            TEXTO VARCHAR2(500) NOT NULL,
                            CRIADO_EM TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);